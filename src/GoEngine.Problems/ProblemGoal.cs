namespace GoEngine.Problems;

using GoEngine.Core;

/// <summary>Цель задачи на жизнь и смерть.</summary>
/// <remarks>
/// Цель определяет, что считается успехом, и как это проверяется по правилам движка
/// (<see cref="ProblemChecker"/>): <see cref="Capture"/> — камни целевой группы исчезли с доски,
/// <see cref="Live"/> — защищающийся успевает построить два глаза за объявленный горизонт
/// (<see cref="ProblemLife"/>), <see cref="Dead"/> — атакующий не даёт построить два глаза за тот же
/// горизонт либо форсирует захват, <see cref="Survive"/> — защищающийся не теряет группу за горизонт.
/// Горизонт и окно ходов объявляются в задаче: без этой пары приговор невоспроизводим.
/// </remarks>
public sealed class ProblemGoal : Enumeration
{
    /// <summary>Убить целевую группу: в решённой позиции её камней на доске нет.</summary>
    public static ProblemGoal Capture { get; } = new(1, nameof(Capture), "убить группу");

    /// <summary>Обеспечить жизнь: у целевой группы должно быть два настоящих глаза.</summary>
    public static ProblemGoal Live { get; } = new(2, nameof(Live), "обеспечить жизнь группы");

    private ProblemGoal(int id, string name, string descriptions)
        : base(id, name, descriptions)
    {
    }

    /// <summary>Убить целевую группу, не снимая её: защищающийся не может построить два глаза.</summary>
    /// <remarks>
    /// Отличие от <see cref="Capture"/>: камни цели остаются на доске, важен результат — группа мертва.
    /// Проверяется перебором: защищающийся играет первым и не может форсировать два глаза за
    /// заявленную границу <see cref="Problem.CheckDepth"/>; граница ограничена, и это записано в задаче.
    /// </remarks>
    public static ProblemGoal Dead { get; } = new(3, nameof(Dead), "убить группу, не снимая: двух глаз у неё быть не может");

    /// <summary>Построить два глаза за горизонт: жизнь формой, а не по детектору слоя AI.</summary>
    /// <remarks>
    /// Отличие от <see cref="Live"/>: там жизнь подтверждается глазным детектором <c>AI</c> в листе
    /// (он консервативен и настоящие глаза формой часто не видит), а здесь защищающийся должен
    /// <b>успеть построить два глаза за объявленный горизонт</b> при противодействии соперника
    /// (<see cref="ProblemLife.CanForceTwoEyes"/>). Глаз считается строго по границе и по входу
    /// в область; границы критерия записаны в <c>PROBLEMS.md</c>. Цель добавлена отдельно, чтобы
    /// не менять смысл уже проверенных задач библиотеки.
    /// </remarks>
    public static ProblemGoal Eyes { get; } = new(6, nameof(Eyes), "построить два глаза за горизонт");

    /// <summary>Спасти камни: защищающийся не теряет группу за объявленный горизонт.</summary>
    /// <remarks>
    /// Отличие от <see cref="Live"/>: жизнь здесь не обязательно строится двумя глазами — группа может
    /// уйти от захвата бегством или борьбой. Приговор выносит <see cref="ProblemLife.CanSurvive"/>:
    /// атакующий ходит первым и за объявленный горизонт не снимает группу. Так формулируются задачи
    /// сайтов вида «спасти камни в углу», где два глаза появляются много позже горизонта.
    /// </remarks>
    public static ProblemGoal Survive { get; } = new(5, nameof(Survive), "спасти камни: группа не должна погибнуть за горизонт");

    /// <summary>Добиться ко-борьбы: в листе решающий может создать ко.</summary>
    /// <remarks>
    /// Ко — не «глаза» и не «снятие»: решающий выигрывает борьбу, если приводит позицию к ко.
    /// Критерий механический и считается правилами движка: в листе есть ход решающего, снимающий
    /// ровно один камень, ответ на который восстанавливает прежнюю позицию и потому запрещён
    /// правилом ко (<see cref="ProblemGoalCheck.KoAvailable"/>). Задачи с этой целью описывают
    /// борьбу, где ни жизнь, ни смерть иначе не формулируются.
    /// </remarks>
    public static ProblemGoal Ko { get; } = new(4, nameof(Ko), "добиться ко-борьбы");

    /// <summary>Задача по решению источника: движок проверяет форму, а не исход.</summary>
    /// <remarks>
    /// <para>
    /// Так оформляются задачи, у которых решение известно из внешнего источника (сайт, книга,
    /// задачник), а машинного критерия исхода нет: перебор показал, что ни снятие группы, ни два
    /// глаза, ни ко за доступный горизонт не форсируются, а смысл задачи — борьба, бегство и темпы.
    /// </para>
    /// <para>
    /// Движок в этом виде подтверждает <b>только форму</b>: ходы линии легальны, стороны
    /// чередуются, дерево не пусто, у задачи есть источник и формулировка. Исход движком
    /// <b>не</b> доказан, и это обязано быть видно игроку: в списке задач такие задачи помечаются
    /// словами «по решению источника» — короче прежней приписки «движком не проверялось»,
    /// которая повторялась у каждой задачи и ничего не различала (замечание пользователя 2026-10-02).
    /// </para>
    /// <para>
    /// Следствие, которое нельзя скрывать: у задачи могут быть другие правильные продолжения, и
    /// приложение их отклонит — принимается ровно линия источника.
    /// </para>
    /// </remarks>
    public static ProblemGoal Reference { get; } = new(7, nameof(Reference), "по решению источника");

    /// <summary>Все цели задач.</summary>
    public static IReadOnlyList<ProblemGoal> All { get; } = [Capture, Live, Dead, Ko, Survive, Eyes, Reference];
}
