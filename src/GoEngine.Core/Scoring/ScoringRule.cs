namespace GoEngine.Core;

/// <summary>Система подсчёта партии: японская (территория с пленными) или китайская (площадь).</summary>
/// <remarks>
/// <para>
/// Правила вида спорта го различают две традиции подсчёта. При японской за каждого пленника и за
/// каждый камень, снятый как мёртвый в заключительной позиции, добавляется очко; камни на доске
/// очков не приносят. При китайской очко приносит каждый свой камень, оставшийся на доске, и каждая
/// окружённая точка, а пленные отдельно не считаются. Территория в обеих системах — пустые участки,
/// в том числе освободившиеся из-под мёртвых камней.
/// </para>
/// <para>
/// Систему выбирает регламент турнира. В турнирах РФ чаще объявляют японскую, поэтому основной
/// в приложении объявлена она (<see cref="Japanese"/>); китайская (<see cref="Chinese"/>) считается
/// рядом и не прячется. На доигранной позиции разница между ними равна разнице числа выставленных
/// сторонами камней — 0 или 1 очко, поэтому показывать обе величины рядом честно.
/// </para>
/// <para>
/// Коми системой не задаётся: его размер определяет регламент встречи. Значения по умолчанию
/// в приложении (7.5 на 19×19, 5.5 на 13×13 и 9×9) — из <c>GO_RULES.md</c>, п. 10; в турнирах РФ
/// на 19×19 типично коми 6.5, и его игрок выставляет в настройках.
/// </para>
/// </remarks>
public sealed class ScoringRule : Enumeration
{
    /// <summary>Японская традиция: территория плюс пленные, камни на доске очков не приносят.</summary>
    public static ScoringRule Japanese { get; } = new(1, nameof(Japanese), "Территория и пленные: так считают большинство турниров РФ");

    /// <summary>Китайская традиция: каждый камень на доске и каждая окружённая точка.</summary>
    public static ScoringRule Chinese { get; } = new(2, nameof(Chinese), "Площадь: свои камни на доске плюс окружённые точки");

    /// <summary>Создаёт систему подсчёта.</summary>
    /// <param name="id">Числовой идентификатор элемента.</param>
    /// <param name="name">Имя элемента для файла настроек.</param>
    /// <param name="descriptions">Описание для интерфейса.</param>
    private ScoringRule(int id, string name, string? descriptions = null)
        : base(id, name, descriptions)
    {
    }
}
