using GoEngine.Core;

namespace GoEngine.App.Services;

/// <summary>Согласование подсчёта: помеченные мёртвые камни и подтверждённый итог партии.</summary>
/// <remarks>
/// <para>
/// Партия, завершённая двумя пасами, сама не заканчивается: стороны согласуют мёртвые группы
/// (<c>GO_RULES.md</c>, пп. 7–9). Здесь живёт ровно это согласование — пометки, предложение
/// перебора и подтверждённый итог. Панель партии показывает его состояние строками и разметкой,
/// а пометок не хранит: счёт, территория и пленные читают одно место, и разойтись им нечем.
/// </para>
/// <para>
/// Мёртвые группы помечает программа, а не человек: перебор <see cref="Endgame.ProposeDead(Board)"/>
/// отвечает на вопрос по правилам, и ответ годится в любой позиции — и в идущей партии, и после
/// двух пасов. Игроку нужен взгляд на партию до её конца: сколько территории у сторон и какие
/// группы уже не спасти, — поэтому предложение считается при любом состоянии партии
/// (жалоба пользователя 2026-10-02: «определять мёртвую группу должна программа»).
/// </para>
/// <para>
/// Оценка постоянная: предложение мёртвых считается для любой позиции, а не только после двух
/// пасов, и запускается само — игрок ничего не нажимает, чтобы увидеть состояние доски
/// (D-070). Оно считается один раз на позицию и переиспользуется до смены позиции; на идущей
/// партии действует предохранитель оценки, после конца — окончательный (D-068).
/// </para>
/// <para>
/// Шага подтверждения нет: как только партия завершена, итог назван — мёртвые группы определены
/// программой, счёт и победитель показаны сразу. Правка пометок кликом остаётся правом игрока,
/// а не обязанностью: клик после конца партии меняет пометку и пересчитывает итог тут же.
/// </para>
/// <para>
/// Пометки относятся к конкретной позиции, а не к партии вообще: любое изменение позиции
/// (ход, отмена, возврат, загрузка, новая партия) начинает согласование заново — это делает
/// <see cref="Sync"/>. Мёртвые камни не снимаются с доски молча: их помечает перебор или игрок
/// кликом, и клик игрока — истина в последней инстанции для этой позиции.
/// </para>
/// <para>
/// Запрошенное предложение считается <b>лениво</b>: <see cref="Sync"/> только запоминает позицию
/// а перебор запускается при первом чтении пометок, территории или счёта и запоминается до смены
/// позиции. Так загрузка партии, отмена хода и смена настроек, которые никто не показал игроку,
/// не стоят перебора вовсе.
/// </para>
/// <para>
/// Итог по согласованным мёртвым считает <c>Core</c>, но пленных и коми знает партия, поэтому
/// расчёт приходит сюда делегатом. Служба не тащит в себя <see cref="GameState"/>: ей довольно
/// доски, состояния партии и умения посчитать итог по списку мёртвых.
/// </para>
/// </remarks>
public sealed class ScoringAgreement
{
    /// <summary>Считает итог партии по согласованным мёртвым камням.</summary>
    private readonly Func<IReadOnlyCollection<Point>, FinalScore> _finalize;

    /// <summary>Помеченные мёртвыми камни: набор, потому что спрашивают «помечена ли эта точка».</summary>
    private readonly HashSet<Point> _dead = [];

    /// <summary>Помеченные камни в порядке обхода доски: список для вида, а не для поиска.</summary>
    private IReadOnlyList<Point> _deadPoints = [];

    /// <summary>Сколько раз менялись пометки мёртвых: по этому счётчику вид перерисовывает доску.</summary>
    private int _deadRevision;

    /// <summary>Доска, для которой посчитано предложение мёртвых: ключ кэша «одно предложение на позицию».</summary>
    /// <remarks>
    /// Кэш нужен из-за цены вопроса: <see cref="Endgame.ProposeDead(Board)"/> перебирает до 20 000 позиций
    /// на группу. Счёт, территория и пленные читаются на каждое изменение свойства и на каждую
    /// перерисовку, поэтому перебор в них недопустим: предложение считается один раз на позицию
    /// и дальше только переиспользуется.
    /// </remarks>
    private Board? _proposalBoard;

    /// <summary>Состояние партии, для которого посчитано предложение мёртвых.</summary>
    /// <remarks>
    /// Пара «доска + состояние» — ключ кэша. Отмена хода возвращает ту же самую доску (экземпляр
    /// сохраняется), но партия снова идёт: по одному лишь экземпляру доски кэш вернул бы
    /// предложение для другого состояния (регрессия поймана при рефакторинге фазы 13).
    /// </remarks>
    private GameStatus? _proposalStatus;

    /// <summary>Предложение мёртвых для доски <see cref="_proposalBoard"/>.</summary>
    private IReadOnlyList<Point> _proposal = [];

    /// <summary>Сколько раз перебор предлагал мёртвые группы за партию.</summary>
    private int _deadProposalCount;

    /// <summary>Доска подсчёта, посчитанная для текущих пометок, или <c>null</c>, если пометок нет.</summary>
    private Board? _scoringBoard;

    /// <summary>Позиция и ревизия пометок, для которых посчитана доска подсчёта.</summary>
    private (Board Board, int Revision)? _scoringBoardKey;

    /// <summary>Позиция согласования: доска, к которой относятся пометки.</summary>
    private Board _board;

    /// <summary>Доска, для которой поставлены текущие пометки: смена доски их обнуляет.</summary>
    /// <remarks>
    /// Отдельное поле, а не сравнение с <see cref="_board"/>: доска неизменяема, но отмена хода
    /// возвращает прежний экземпляр — по нему одному нельзя понять, что позиция сменилась.
    /// </remarks>
    private Board? _markedBoard;

    /// <summary>Пометки соответствуют текущей позиции: пересобирать их не нужно.</summary>
    /// <remarks>
    /// Флаг ленивости: <see cref="Sync"/> его снимает, первое чтение пометок — ставит обратно,
    /// уже пересобрав набор. Пока он снят, в <see cref="_dead"/> лежат пометки прежней позиции,
    /// и наружу они не выходят: все читатели начинают с <see cref="EnsureMarks"/>.
    /// </remarks>
    private bool _marksReady;

    /// <summary>Пометки, поставленные игроком кликом: их нельзя терять при пересчёте предложения.</summary>
    /// <remarks>
    /// Ручные пометки и предложение перебора живут в одном наборе <see cref="_dead"/>, но приходят
    /// из разных источников: предложение пересчитывается на каждую смену состояния, а клики игрока
    /// обязаны сохраниться до смены позиции.
    /// </remarks>
    private readonly HashSet<Point> _manual = [];

    /// <summary>Камни, которые игрок снял с пометки: предложение перебора их больше не возвращает.</summary>
    /// <remarks>
    /// Без этого набора клик «эта группа жива» отменялся бы следующим пересчётом предложения:
    /// перебор снова предлагал бы те же камни, и счёт возвращался бы к неверному.
    /// </remarks>
    private readonly HashSet<Point> _removed = [];

    /// <summary>Состояние партии на момент согласования.</summary>
    private GameStatus _status;

    /// <summary>Создаёт согласование для позиции партии.</summary>
    /// <param name="board">Текущая позиция.</param>
    /// <param name="status">Состояние партии.</param>
    /// <param name="finalize">Как посчитать итог по согласованным мёртвым камням.</param>
    /// <exception cref="ArgumentNullException">Позиция, состояние или расчёт не заданы.</exception>
    /// <remarks>
    /// Позиция передаётся сразу и тут же запоминается: согласования без позиции не бывает,
    /// а предложение перебора нужно уже на первом чтении счёта. Сам перебор при создании
    /// не запускается — он ленивый (см. <see cref="EnsureMarks"/>) и считается один раз на позицию.
    /// </remarks>
    public ScoringAgreement(
        Board board,
        GameStatus status,
        Func<IReadOnlyCollection<Point>, FinalScore> finalize)
    {
        ArgumentNullException.ThrowIfNull(board);
        ArgumentNullException.ThrowIfNull(status);
        ArgumentNullException.ThrowIfNull(finalize);

        _finalize = finalize;
        _board = board;
        _status = status;

        // Синхронизация — единственный путь, которым считаются пометки и предложение: второй
        // такой же расчёт в конструкторе разошёлся бы с ним при первой же правке.
        Sync(board, status);
    }

    /// <summary>Пометки мёртвых изменились.</summary>
    /// <remarks>
    /// Событие поднимает только правка пометок кликом. Смену позиции (<see cref="Sync"/>) вызывающий
    /// сообщает виду сам: он и так меняет всю панель партии, и второе сообщение об одном и том же
    /// заставило бы вид перерисоваться дважды.
    /// </remarks>
    public event EventHandler? Changed;

    /// <summary>Помеченные мёртвыми камни: точка означает всю свою группу.</summary>
    /// <remarks>Набор, а не список: по нему спрашивают «помечена ли точка», а не «что за чем идёт».</remarks>
    public IReadOnlyCollection<Point> DeadStones
    {
        get
        {
            EnsureMarks();

            return _dead;
        }
    }

    /// <summary>Помеченные мёртвыми камни в порядке обхода доски.</summary>
    public IReadOnlyList<Point> DeadPoints
    {
        get
        {
            EnsureMarks();

            return _deadPoints;
        }
    }

    /// <summary>Сколько раз менялись пометки мёртвых.</summary>
    /// <remarks>
    /// Вид перерисовывает доску по этому счётчику: список <see cref="DeadPoints"/> может остаться
    /// тем же объектом, и подписка на него одного изменения не заметит.
    /// </remarks>
    public int DeadRevision
    {
        get
        {
            EnsureMarks();

            return _deadRevision;
        }
    }

    /// <summary>Сколько раз перебор предлагал мёртвые группы за партию.</summary>
    /// <remarks>
    /// Открыт ради проверок: предложение мёртвых — самый дорогой перебор в подсчёте
    /// (<see cref="Endgame.ProposeDead(Board)"/>, до 20 000 позиций на группу), и он обязан считаться
    /// один раз на позицию. Счётчик растёт в тот момент, когда перебор действительно идёт —
    /// на первом чтении пометок, территории или счёта для новой позиции, — поэтому на чтение
    /// готового предложения он не меняется. Тест читает счёт, территорию и пленных десятки раз
    /// и требует, чтобы счётчик вырос ровно один раз, а проверочный режим печатает его рядом
    /// с разбором.
    /// </remarks>
    public int DeadProposalCount => _deadProposalCount;

    /// <summary>Предохранитель перебора для текущего состояния партии.</summary>
    /// <remarks>
    /// <para>
    /// Правило одно и живёт здесь, а не в месте вызова: пока партия идёт, предложение — оценка
    /// перспективы, и у неё предохранитель оценки (<see cref="Endgame.EstimateNodesPerPosition"/>);
    /// в завершённой партии предложение решает судьбу счёта, поэтому предохранитель окончательный
    /// (<see cref="Endgame.MaxNodesPerPosition"/>).
    /// </para>
    /// <para>
    /// Оба — предохранители, а не ограничители: на проверенном корпусе ни один не срабатывает,
    /// а исчерпанный бюджет означает «не доказано», то есть группа остаётся живой.
    /// </para>
    /// </remarks>
    public int DeadProposalBudget =>
        _status == GameStatus.InProgress ? Endgame.EstimateNodesPerPosition : Endgame.MaxNodesPerPosition;

    /// <summary>Итог по текущей позиции: считается по пометкам и меняется вместе с ними.</summary>
    /// <remarks>
    /// Считает <c>Core</c> одной функцией от доски, пометок, пленных партии и системы подсчёта.
    /// Подтверждённого снимка нет: после конца партии итог уже окончательный (D-070), а правка
    /// пометки кликом пересчитывает его сразу — замороженное число разошлось бы с доской.
    /// </remarks>
    public FinalScore CurrentScore => _finalize(DeadStones);

    /// <summary>Доска подсчёта: без помеченных мёртвых камней.</summary>
    /// <remarks>
    /// Территория и владение считаются по ней, а не по игровой доске: мёртвый камень внутри
    /// чужого владения не должен отменять территорию соперника. Доска кэшируется по позиции
    /// и ревизии пометок: оценка теперь постоянная, панель читает разметку, счёт и пленные
    /// на каждое изменение, а сборка доски с обходом групп стоит дороже самого чтения. Ключ
    /// из двух частей — потому что отмена хода возвращает прежний экземпляр доски, но партия
    /// при этом другая.
    /// </remarks>
    public Board ScoringBoard
    {
        get
        {
            EnsureMarks();

            if (_scoringBoardKey is { } key && ReferenceEquals(key.Board, _board) && key.Revision == _deadRevision)
            {
                return _scoringBoard!;
            }

            var cleared = _dead.Count == 0 ? _board : Endgame.ClearedBoard(_board, _dead);

            _scoringBoard = cleared;
            _scoringBoardKey = (_board, _deadRevision);

            return cleared;
        }
    }

    /// <summary>Приводит согласование в соответствие с позицией партии.</summary>
    /// <param name="board">Текущая позиция.</param>
    /// <param name="status">Состояние партии.</param>
    /// <exception cref="ArgumentNullException">Позиция или состояние не заданы.</exception>
    /// <remarks>
    /// <para>
    /// Пометки относятся к позиции: любой ход, отмена, возврат, загрузка и новая партия начинают
    /// счёт заново — мёртвая группа одной позиции ничего не значит в другой. Ручные пометки
    /// убираются вместе с позицией, предложение перебора — тоже.
    /// </para>
    /// <para>
    /// Перебора здесь нет: метод только запоминает позицию, а сам перебор запустится при первом
    /// чтении пометок, территории или счёта (<see cref="EnsureMarks"/>). Иначе каждый ход игрока
    /// ждал бы полного перебора, хотя счёт может быть никем и не спрошен.
    /// </para>
    /// <para>
    /// Итог не сбрасывается и не подтверждается: подтверждённого снимка больше нет, счёт всегда
    /// считается по текущим пометкам (D-070).
    /// </para>
    /// </remarks>
    public void Sync(Board board, GameStatus status)
    {
        ArgumentNullException.ThrowIfNull(board);
        ArgumentNullException.ThrowIfNull(status);

        _board = board;
        _status = status;

        // Пометки живут в границах позиции: сменилась доска — начинаем с чистого листа.
        // Отмена хода возвращает прежний экземпляр доски, поэтому сравнивается именно экземпляр:
        // новая позиция — новые пометки, та же — прежние.
        if (!ReferenceEquals(_markedBoard, board))
        {
            _markedBoard = board;
            _dead.Clear();
            _manual.Clear();
            _removed.Clear();
        }

        // Пометки пересобираются не здесь, а на первом чтении: доска и состояние уже новые,
        // и перебор предложения пойдёт по ним.
        _marksReady = false;
    }

    /// <summary>Помечает или снимает пометку группы, которой принадлежит точка.</summary>
    /// <param name="point">Точка на доске: клик игрока по камню.</param>
    /// <returns><c>true</c>, если пометки изменились.</returns>
    /// <remarks>
    /// Помечается вся группа: камень живёт и умирает вместе с ней, частично мёртвой группы не
    /// бывает. Повторный клик снимает пометку. Пометка доступна в любой момент — и в идущей
    /// партии, и после её конца: программа предлагает мёртвых сама, а игрок вправе поправить,
    /// и счёт пересчитывается сразу. После конца партии правка меняет уже названный итог
    /// (D-070): это право игрока, а не обязанность. По пустой точке и по точке вне доски метод
    /// ничего не делает и возвращает <c>false</c>: виду не нужно самому проверять состояние партии.
    /// </remarks>
    public bool ToggleDeadAt(Point point)
    {
        if (point.IsOnBoard(_board.Size) is false || _board.At(point) == StoneColor.Empty)
        {
            return false;
        }

        // Клик отвечает на вопрос «помечена ли группа»: набор пометок обязан быть собран.
        EnsureMarks();

        // Пометки — часть позиции: если позиция сменилась, старые уже убраны в Sync.
        _markedBoard = _board;

        var stones = GroupTracker.FindGroup(_board, point).Stones;

        if (_dead.Contains(point))
        {
            foreach (var stone in stones)
            {
                _ = _manual.Remove(stone);

                // Снятая пометка запоминается: иначе пересчёт предложения вернул бы её обратно,
                // и клик игрока «эта группа жива» не имел бы силы.
                _ = _removed.Add(stone);
                _ = _dead.Remove(stone);
            }
        }
        else
        {
            foreach (var stone in stones)
            {
                _ = _manual.Add(stone);
                _ = _removed.Remove(stone);
                _ = _dead.Add(stone);
            }
        }

        _deadRevision++;
        RefreshDeadPoints();
        Notify();

        return true;
    }

    /// <summary>Собирает пометки для текущей позиции, если это ещё не сделано.</summary>
    /// <remarks>
    /// <para>
    /// Единственное место, откуда запускается перебор предложения. Пометки собираются заново
    /// из двух источников: ручных кликов игрока и предложения перебора. Ручные пометки — основа:
    /// они переживают пересчёт и снимаются только вместе с позицией; снятые игроком камни
    /// (<see cref="_removed"/>) предложение не возвращает.
    /// </para>
    /// <para>
    /// Ревизия растёт, только если пометки действительно изменились: вид перерисовывает доску
    /// по ней, и лишний рост заставлял бы рисовать одно и то же дважды. Набор и список для вида
    /// обновляются всегда вместе: «умный» ранний выход по одному лишь сравнению наборов оставлял
    /// список прежним — доска показывала пометки, которых в счёте уже нет (регрессия, поймана
    /// тестом Синхронизация_Другой_Позиции_Сбрасывает_Пометки).
    /// </para>
    /// </remarks>
    private void EnsureMarks()
    {
        if (_marksReady)
        {
            return;
        }

        _marksReady = true;

        HashSet<Point> rebuilt = [];
        rebuilt.UnionWith(_manual);

        foreach (var stone in Proposal)
        {
            if (!_removed.Contains(stone))
            {
                _ = rebuilt.Add(stone);
            }
        }

        var changed = !_dead.SetEquals(rebuilt);

        _dead.Clear();
        _dead.UnionWith(rebuilt);
        RefreshDeadPoints();

        if (changed)
        {
            _deadRevision++;
        }
    }

    /// <summary>Предложение мёртвых для текущей позиции: считается один раз и переиспользуется.</summary>
    /// <remarks>
    /// <para>
    /// Кэш держится на паре «экземпляр доски + состояние партии»: доска неизменяема, и её экземпляр
    /// меняется ровно тогда, когда меняется позиция (ход, отмена, возврат, загрузка, новая партия),
    /// а состояние отличает отменённый ход, вернувший ту же доску в игру. Поэтому геттеры счёта,
    /// территории и пленных читают готовое предложение, а не запускают перебор заново: считать
    /// его на каждое чтение свойства значило бы перебирать десятки тысяч позиций на каждую
    /// перерисовку панели.
    /// </para>
    /// <para>
    /// Оценка постоянная (D-070): предложение считается для любой позиции и запоминается до её
    /// смены. Предохранитель выбирается по состоянию партии — в игре дешёвый, после конца полный
    /// (<see cref="DeadProposalBudget"/>).
    /// </para>
    /// <para>
    /// Перебор предлагает только доказанные группы и ничего не утверждает о сэки и глазах:
    /// ложное «мёртвая» испортило бы счёт молча, поэтому предложение осторожное, а границы
    /// доказательства у него прежние (<see cref="Endgame.ProposeDead(Board)"/>: до двух дамэ, горизонт
    /// шесть полуходов, 20 000 позиций на группу, без ко и дальних угроз). Сверху работа ограничена
    /// предохранителем (<see cref="DeadProposalBudget"/>): окончательным в завершённой партии
    /// и меньшим — у оценки идущей партии. На проверенном корпусе не срабатывает ни один из них:
    /// они нужны патологической доске, где групп-кандидатов десятки.
    /// </para>
    /// </remarks>
    private IReadOnlyList<Point> Proposal
    {
        get
        {
            if (ReferenceEquals(_proposalBoard, _board) && _proposalStatus == _status)
            {
                return _proposal;
            }

            _proposalBoard = _board;
            _proposalStatus = _status;

            // Бюджет выбирается по состоянию партии: оценка в игре — дешёвая, окончательное
            // предложение — полное (см. DeadProposalBudget).
            _proposal = Endgame.ProposeDead(_board, DeadProposalBudget);
            _deadProposalCount++;

            return _proposal;
        }
    }

    /// <summary>Обновляет список помеченных камней для вида: порядок — как у обхода доски.</summary>
    private void RefreshDeadPoints() =>
        _deadPoints = [.. _dead.OrderBy(static point => point.Y).ThenBy(static point => point.X)];

    /// <summary>Сообщает об изменении пометок мёртвых.</summary>
    private void Notify() => Changed?.Invoke(this, EventArgs.Empty);
}
