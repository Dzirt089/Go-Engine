namespace GoEngine.App.Rendering;

/// <summary>Итог партии для подсветки доски: она выиграна, проиграна или ничья.</summary>
/// <remarks>
/// Живёт в слое рисования, а не в модели представления: отрисовка не должна знать ни про счёт,
/// ни про цвет игрока — она только красит доску по готовому ответу. Решение принимает
/// <c>MainViewModel</c>, а элемент управления передаёт его сюда.
/// </remarks>
public enum BoardOutcome
{
    /// <summary>Партия идёт: доска не подсвечивается.</summary>
    None,

    /// <summary>Партия выиграна игроком.</summary>
    Win,

    /// <summary>Партия проиграна игроком.</summary>
    Loss,

    /// <summary>Ничья.</summary>
    Draw
}
