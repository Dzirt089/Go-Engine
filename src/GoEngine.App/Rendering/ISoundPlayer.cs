namespace GoEngine.App.Rendering;

/// <summary>Проигрыватель звука ходов.</summary>
/// <remarks>
/// Порт разделяет «что звучит» и «чем звучит»: библиотека интерфейса знает только байты WAV,
/// а способ воспроизведения выбирает голова — <c>winmm</c> на Windows, внешний проигрыватель на
/// Linux, <c>SoundPool</c> на Android. Так звук не тянет в интерфейс ни одной платформенной
/// зависимости, а на системе без звуковой подсистемы остаётся тишина, а не отказ запуска.
/// </remarks>
public interface ISoundPlayer
{
    /// <summary>Проигрывает звук из памяти.</summary>
    /// <param name="wav">Байты файла WAV (PCM 16 бит); пустая память — играть нечего.</param>
    /// <remarks>
    /// Реализация <b>не имеет права</b> выпускать исключение наружу: нет звуковой подсистемы,
    /// устройство занято, проигрыватель не найден — всё это молча пропускается. Звук — украшение,
    /// а не часть игры, и падать из-за него нельзя (та же логика, что у логирования).
    /// Вызывающий (обвязка <see cref="StoneSoundPlayer"/>) зовёт проигрыватель из фонового
    /// потока, поэтому долгое воспроизведение не задерживает интерфейс, но реализация обязана
    /// быть потокобезопасной: два хода подряд могут прийти почти одновременно.
    /// </remarks>
    public void Play(ReadOnlyMemory<byte> wav);
}

/// <summary>Проигрыватель-заглушка: не играет ничего.</summary>
/// <remarks>
/// Значение по умолчанию для <c>App.Sound</c>: пока голова не задала свой проигрыватель (или
/// у системы его нет) звука нет, но весь остальной код остаётся одним и тем же. Нужен ещё
/// и тестам, и голове, которая знает, что система отключила анимации: тогда звук не играется,
/// потому что играть его нечем.
/// </remarks>
public sealed class SilentSoundPlayer : ISoundPlayer
{
    /// <inheritdoc />
    /// <remarks>Намеренно пусто: тишина и есть поведение заглушки.</remarks>
    public void Play(ReadOnlyMemory<byte> wav)
    {
        // Тело пустое осознанно: параметр не проверяется, потому что заглушке всё равно,
        // что ей передали.
    }
}
