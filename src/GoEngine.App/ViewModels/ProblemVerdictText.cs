namespace GoEngine.App.ViewModels;

/// <summary>Чистка разбора хода задачи перед показом: длинные оговорки домена игроку не нужны.</summary>
/// <remarks>
/// <para>
/// Разбор хода собирает домен задач (<c>GoEngine.Problems</c>): он знает позицию, дыхания и цель.
/// В конце строки домен честно оговаривает, что у задачи из источника исход движком не проверяется,
/// и ход взят из линии решения. Для новичка эта фраза ничего не значит: он видит «Верно: D9 — …;
/// дыхания не изменились — он из линии решения источника, а цель достигается всей линией»
/// и не понимает, ход-то правильный или нет (N6 отчёта QA 2026-10-17).
/// </para>
/// <para>
/// Поэтому оговорка снимается на выходе, в слое интерфейса. Домен при этом не меняется: его
/// собственные проверки текста продолжают видеть полную формулировку, а игрок — короткую.
/// </para>
/// </remarks>
internal static class ProblemVerdictText
{
    /// <summary>Оговорка домена о задаче из источника, которую игроку читать незачем.</summary>
    private const string SourceLineClause =
        " — он из линии решения источника, а цель достигается всей линией";

    /// <summary>Убирает из разбора хода оговорку про линию решения источника.</summary>
    /// <param name="feedback">Разбор хода, собранный доменом задач.</param>
    /// <returns>Тот же разбор без служебной оговорки.</returns>
    /// <remarks>
    /// Замена точная, а не по словам «линия» и «источник»: эти слова встречаются и в полезных
    /// пояснениях, и вырезать их значило бы менять смысл разбора.
    /// </remarks>
    public static string Shorten(string feedback)
    {
        ArgumentNullException.ThrowIfNull(feedback);

        return feedback.Replace(SourceLineClause, string.Empty, StringComparison.Ordinal);
    }
}
